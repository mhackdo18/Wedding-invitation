/*
# Add a customizable invitation email button label

1. New Columns
- `email_settings.invitation_button_label` stores the text shown on the automatically generated invitation link button in HTML emails and plain-text email fallbacks.

2. Modified Tables
- `email_settings`: adds one nullable text setting with a safe default for existing and new email configurations.

3. Security
- No new tables or policies are introduced. Existing `email_settings` row-level security and access rules remain unchanged.

4. Important Notes
- Existing emails keep the current label, “Open your invitation”, through the database default.
- The value is presentation text only; the invitation URL remains generated by the server for each guest.
*/

ALTER TABLE email_settings
  ADD COLUMN IF NOT EXISTS invitation_button_label text NOT NULL DEFAULT 'Open your invitation';